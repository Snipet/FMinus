// Generates the site's content from the repository (site/..) into src/lib/generated/, which is rebuilt from nothing
// every time (npm run dev and npm run build run this first):
//   api.json         include/fminus/FMinus.h: every public declaration, its comment and its signature
//   grammar.json     src/frontend/Parser.y and Lexer.l: rules, railroad diagrams, tokens, precedence, the scanner
//   internals.json   the documents' list and docs/README.md; docs/<slug>.json, one document each
//   home.json        the README's opening paragraph, and a line on each section
//   search.json      every heading and declaration, for the search box
//   highlight.css    the colours of the highlighted code, light and dark
// A source the generators can't read, or a public declaration with no comment, stops the build with the file, the line
// and what to change.
import fs from 'node:fs';
import { performance } from 'node:perf_hooks';
import { base, generatedDir, GenerateError, writeJson, writeText } from './lib/repo.js';

const started = performance.now();
try {
	const highlight = await import('./lib/highlight.js');
	const { generateApi } = await import('./lib/api.js');
	const { generateGrammar } = await import('./lib/grammar.js');
	const { generateDocs } = await import('./lib/docs.js');

	const { api, search: apiSearch, warnings: apiWarnings } = generateApi(highlight);
	const { grammar, search: grammarSearch, warnings: grammarWarnings } = generateGrammar(highlight);
	const warnings = [...apiWarnings, ...grammarWarnings];
	const docs = generateDocs(highlight);

	fs.rmSync(generatedDir, { recursive: true, force: true });
	writeJson('api.json', api);
	writeJson('grammar.json', grammar);
	writeJson('internals.json', { index: docs.index, list: docs.list });
	for (const page of docs.pages) writeJson(`docs/${page.slug}.json`, page);
	writeJson('home.json', {
		introHtml: docs.intro,
		api: { summary: api.summary, file: api.file, count: api.declarations.length },
		grammar: { summary: grammar.summary, rules: grammar.rules.length, tokens: grammar.tokens.length },
		docs: docs.list,
	});
	writeJson('search.json', [...apiSearch, ...grammarSearch, ...docs.search]);
	writeText('highlight.css', `/* Generated by scripts/generate.js: Shiki's colours, as classes. */\n${highlight.highlightCss()}\n`);

	for (const w of warnings) console.warn(`generate: warning: ${w}`);
	if (highlight.unknownLanguages.size) {
		console.warn(`generate: warning: code fences in a language the site does not highlight: ${[...highlight.unknownLanguages].join(', ')}`);
	}
	const ms = Math.round(performance.now() - started);
	console.log(`generate: ${api.declarations.length} declarations, ${grammar.rules.length} rules, ${grammar.tokens.length} tokens, ` +
		`${docs.pages.length + 1} documents in ${ms} ms (base path '${base}')`);
} catch (error) {
	if (error instanceof GenerateError) {
		console.error(`generate: ${error.message}`);
		process.exit(1);
	}
	throw error;
}
